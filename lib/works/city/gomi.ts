const nthOfMonth = (d: Date) => Math.floor((d.getDate() - 1) / 7) + 1;

/** kinds collected on a given date for a district */
export function kindsOn(dist: District, d: Date): Kind[] {
  const wd = d.getDay();
  const out: Kind[] = [];
  for (const k of Object.keys(dist.days) as Kind[]) if (dist.days[k]!.includes(wd)) out.push(k);
  if (wd === dist.nthDay && dist.nth.includes(nthOfMonth(d))) out.push('moenai', 'yugai');
  return out;
}

/** next collection date (today counts if before 8:30) */
export function nextDate(dist: District, kind: Kind, now = new Date()): Date | null {
  if (kind === 'sodai' || kind === 'kyoten' || kind === 'none') return null;
  const start = new Date(now);
  start.setHours(0, 0, 0, 0);
  const beforeCutoff = now.getHours() * 60 + now.getMinutes() < 8 * 60 + 30;
  for (let i = beforeCutoff ? 0 : 1; i < 70; i++) {
    const d = new Date(start);
    d.setDate(start.getDate() + i);
    if (kindsOn(dist, d).includes(kind)) return d;
  }
  return null;
}

const W = '日月火水木金土';
export const fmtDate = (d: Date) => `${d.getMonth() + 1}月${d.getDate()}日（${W[d.getDay()]}）`;
export const weekday = (d: Date) => W[d.getDay()];
export function relDay(d: Date, now = new Date()) {
  const a = new Date(now);
  a.setHours(0, 0, 0, 0);
  const diff = Math.round((d.getTime() - a.getTime()) / 864e5);
  return diff === 0 ? ['きょう', 'きょう'] : diff === 1 ? ['あす', 'あした'] : diff === 2 ? ['あさって', 'あさって'] : [`${diff}日後`, `${diff}にち あと`];
}

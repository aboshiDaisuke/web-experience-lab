function bunkoLines() {
  const out: string[] = [];
  const r = rng(77);
  const used = new Set<string>();
  for (let i = 0; out.length < 26 && i < 400; i++) {
    const t = BUNKO_A[Math.floor(r() * BUNKO_A.length)] + BUNKO_B[Math.floor(r() * BUNKO_B.length)];
    if (used.has(t)) continue;
    used.add(t);
    const [au, mk] = BUNKO_AU[Math.floor(r() * BUNKO_AU.length)];
    const st = r() < 0.2 ? 'L' : r() < 0.06 ? 'R1' : '';
    out.push(`913.6|B|${t}|${au}|${mk}|渡り鳥文庫|${2008 + Math.floor(r() * 16)}|${180 + Math.floor(r() * 200)}|${st}|小説,文庫|${BUNKO_BLURB[Math.floor(r() * BUNKO_BLURB.length)]}`);
  }
  return out;
}

function build(): Book[] {
  const out: Book[] = [];
  let id = 1;
  for (const line of [...RAW.trim().split('\n'), ...bunkoLines()]) {
    const [ndc, fmt, title, author, mark, pub, year, pages, st, tags, blurb] = line.split('|');
    const cls = clsOf(ndc);
    const seed = hash(title);
    out.push(
      makeBook(id++, {
        title, author, mark, ndc, cls, pub, year: Number(year), pages: Number(pages), fmt: fmt as Fmt,
        status: parseStatus(st, seed), blurb, tags: tags.split(','),
      }),
    );
  }
  for (const s of SERIES) {
    s.vols.forEach((v, i) => {
      const seed = hash(s.title + v);
      const r = rng(seed);
      const st = s.ref ? 'N' : r() < 0.22 ? 'L' : r() < 0.08 ? 'R1' : '';
      out.push(
        makeBook(
          id++,
          {
            title: s.title, sub: v, author: s.title === '現代日本文学館' ? v : s.author, mark: s.mark, ndc: s.ndc,
            cls: clsOf(s.ndc), pub: s.pub, year: s.year + Math.floor(i / 4), pages: s.pages + Math.round((r() - 0.5) * s.pages * 0.16),
            fmt: s.fmt, status: parseStatus(st, seed), blurb: s.blurb, tags: s.tags, series: s.title, vol: i + 1,
          },
          s,
        ),
      );
    });
  }
  return out;
}


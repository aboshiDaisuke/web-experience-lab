function fold(s: string) {
  return s
    .normalize('NFKC')
    .toLowerCase()
    .replace(/[ァ-ヶ]/g, (c) => String.fromCharCode(c.charCodeAt(0) - 0x60))
    .replace(/\s+/g, '');
}
const index = books.map((b) =>
  fold([b.title, b.sub ?? '', b.author, b.pub, b.ndc, b.blurb, b.tags.join(' '), classes[b.cls].name, shelfHead(b.ndc)].join(' ')),
);
export function search(q: string): number[] {
  const terms = q.trim().split(/[\s　]+/).filter(Boolean);
  if (!terms.length) return [];
  const expanded = terms.map((t) => {
    const f = fold(t);
    const alts = [f];
    for (const [k, v] of synonyms) if (fold(k) === f || (f.length >= 2 && fold(k).startsWith(f) && f.length >= fold(k).length - 1)) alts.push(fold(v));
    return alts;
  });
  const hits: number[] = [];
  books.forEach((b, i) => {
    if (expanded.every((alts) => alts.some((a) => index[i].includes(a)))) hits.push(b.id);
  });
  return hits;
}

// ---------- shelf layout (all units in mm) ----------
export type Placed = { id: number; x: number; row: number; lean: number; face?: boolean };
export type Bay = {
  cls: number;
  part: number;
  x: number;
  w: number;
  rows: { heads: { x: number; label: string }[]; end: number }[];
};
export type Layout = { bays: Bay[]; placed: Placed[]; width: number; rows: number };

export const ROWS = 3;
export const UPRIGHT = 30;
export const ROW_CLEAR = 258;
const FILL = 0.93;
const UNIT = 880;

function ndcKey(b: Book) {
  if (b.ndc === 'E') return 1000 + (b.series ? 0.5 : 0);
  return parseFloat(b.ndc.replace(/[^\d.]/g, '')) || 0;
}

export function layoutShelf(): Layout {
  const bays: Bay[] = [];
  const placed: Placed[] = [];
  let x = UPRIGHT;
  const r = rng(424242);
  const faceRow = 1;
  for (const c of classes) {
    const list = books
      .filter((b) => b.cls === c.n)
      .sort((a, b) => ndcKey(a) - ndcKey(b) || (a.series ?? '').localeCompare(b.series ?? '') || (a.vol ?? 0) - (b.vol ?? 0) || a.mark.localeCompare(b.mark, 'ja'));
    const face = list.find((b) => !b.series && b.fmt !== 'B' && b.fmt !== 'S' && b.year >= 2022) ?? null;
    const spines = list.filter((b) => b !== face);
    const width = (b: Book) => b.t + 0.8;
    const S = spines.reduce((s, b) => s + width(b), 0);
    const faceW = face ? face.d + 50 : 0;
    const parts = Math.max(1, Math.round((S + faceW) / (ROWS * FILL * UNIT)));
    // split into consecutive chunks of similar width
    const chunks: Book[][] = Array.from({ length: parts }, () => []);
    let acc = 0;
    for (const b of spines) {
      const k = Math.min(parts - 1, Math.floor((acc / S) * parts));
      chunks[k].push(b);
      acc += width(b);
    }
    chunks.forEach((chunk, part) => {
      const CS = chunk.reduce((s, b) => s + width(b), 0);
      const fw = part === 0 ? faceW : 0;
      const w = Math.max(240, Math.ceil((CS + fw) / ROWS / FILL / 10) * 10 + 24);
      const cap = Array.from({ length: ROWS }, (_, i) => (i === faceRow ? w - 22 - fw : w - 22));
      const capSum = cap.reduce((a, b) => a + b, 0);
      const target = cap.map((cp) => (CS * cp) / capSum);
      const bay: Bay = { cls: c.n, part, x, w, rows: Array.from({ length: ROWS }, () => ({ heads: [], end: 8 })) };
      let row = 0;
      let cx = 8;
      let rowUsed = 0;
      let lastHead = '';
      let lastHeadX = -999;
      const rowStart = placed.length;
      for (const b of chunk) {
        const need = width(b);
        if (row < ROWS - 1 && (rowUsed + need / 2 > target[row] || cx + need > cap[row])) {
          bay.rows[row].end = cx;
          row++;
          cx = 8;
          rowUsed = 0;
          lastHead = '';
          lastHeadX = -999;
        }
        const head = shelfHead(b.ndc) || c.name;
        if (head !== lastHead) {
          if (cx - lastHeadX > 150 && cx < w - 110) {
            bay.rows[row].heads.push({ x: cx, label: `${b.ndc === 'E' ? 'E' : b.ndc.slice(0, 3)} ${head}` });
            lastHeadX = cx;
          }
          lastHead = head;
        }
        placed.push({ id: b.id, x: x + cx, row, lean: 0 });
        const gap = r() < 0.04 ? 2 : 0;
        cx += need + gap;
        rowUsed += need + gap;
      }
      bay.rows[row].end = cx;
      for (let ri = 0; ri < ROWS; ri++) {
        const inRow = placed.slice(rowStart).filter((p) => p.row === ri);
        const last = inRow[inRow.length - 1];
        const free = cap[ri] + 14 - bay.rows[ri].end;
        if (last && free > 22) {
          const bk = bookById.get(last.id)!;
          last.lean = Math.min(15, (Math.atan((free - 6) / bk.h) * 180) / Math.PI);
        }
      }
      if (face && part === 0) placed.push({ id: face.id, x: x + w - face.d - 20, row: faceRow, lean: 0, face: true });
      bays.push(bay);
      x += w + UPRIGHT;
    });
  }
  return { bays, placed, width: x, rows: ROWS };
}

